"""Pin client egress to an additional public IP, outside the peer NAT table.

``inet netinja_src`` / ``pin`` sits at priority -200, before ``peersrc`` and
before the host MASQUERADE. The peer-egress script never creates or flushes
this table, so rebuilding WireGuard NAT cannot put the primary address back.
"""

from __future__ import annotations

import ipaddress
import json
import os
import re
import shutil
from pathlib import Path
from typing import Any, Callable

from agent.support.process import execute, run as process_run

Runner = Callable[..., Any]
_TABLE = "netinja_src"
_CHAIN = "pin"
_UNIT_NAME = "netinja-srcpin.service"
_UNIT_PATH = Path("/etc/systemd/system") / _UNIT_NAME


def state_path() -> Path:
    override = os.environ.get("NETINJA_PUBLIC_SOURCE_PIN", "").strip()
    if override:
        return Path(override)
    return Path("/var/lib/netinja-agent/public-source-pin.json")


def script_path() -> Path:
    return state_path().with_name("netinja-srcpin.sh")


def load_state(path: Path | None = None) -> dict[str, list[dict[str, Any]]]:
    file = path or state_path()
    if not file.is_file():
        return {"addresses": [], "peers": []}
    try:
        payload = json.loads(file.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {"addresses": [], "peers": []}
    if not isinstance(payload, dict):
        return {"addresses": [], "peers": []}
    return {
        "addresses": _addresses(payload.get("addresses")),
        "peers": _peers(payload.get("peers")),
    }


def save_state(state: dict[str, Any], path: Path | None = None) -> dict[str, list[dict[str, Any]]]:
    clean = {
        "addresses": _addresses(state.get("addresses")),
        "peers": _peers(state.get("peers")),
    }
    file = path or state_path()
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(json.dumps(clean, indent=2) + "\n", encoding="utf-8")
    return clean


def render_script(state: dict[str, Any]) -> str:
    """Shell that rewrites ``inet netinja_src`` and the pinned-address set.

    It never flushes ``inet netinja_egress`` chains. MASQUERADE rules in that
    table consult the set and therefore stop rewriting these addresses.
    """
    addresses = _addresses(state.get("addresses"))
    peers = _peers(state.get("peers"))
    elements = ", ".join(str(row["ip"]) for row in addresses)
    lines = [
        "#!/bin/sh",
        "# Generated by Netinja agent — additional-IP source pin. Do not edit.",
        "set +e",
        "if command -v nft >/dev/null 2>&1; then",
        "  nft add table inet netinja_egress 2>/dev/null || true",
        "  nft add set inet netinja_egress pinned '{ type ipv4_addr; }' 2>/dev/null || true",
        "  nft flush set inet netinja_egress pinned 2>/dev/null || true",
    ]
    if elements:
        lines.append(
            f"  nft add element inet netinja_egress pinned '{{ {elements} }}' 2>/dev/null || true"
        )
    lines.extend([
        f"  nft add table inet {_TABLE} 2>/dev/null || true",
        f"  nft add chain inet {_TABLE} {_CHAIN} "
        '"{ type nat hook postrouting priority -200; policy accept; }" 2>/dev/null || true',
        f"  nft flush chain inet {_TABLE} {_CHAIN} 2>/dev/null || true",
    ])
    for row in addresses:
        address = row["ip"]
        mark = int(row["mark"])
        lines.append(
            f'  nft add rule inet {_TABLE} {_CHAIN} ip saddr {address} '
            f'accept comment "netinja-src-keep-{address}"'
        )
        lines.append(
            f'  nft add rule inet {_TABLE} {_CHAIN} meta mark {hex(mark)} '
            f'snat to {address} accept comment "netinja-src-mark-{mark}"'
        )
    for row in peers:
        host = row["cidr"].split("/", 1)[0]
        lines.append(
            f'  nft add rule inet {_TABLE} {_CHAIN} ip saddr {row["cidr"]} '
            f'snat to {row["snat"]} accept comment "netinja-src-peer-{host}"'
        )
    lines.extend(["  exit 0", "fi", "exit 0", ""])
    return "\n".join(lines)


def _install_enabled() -> bool:
    """The pin is a Linux nft table. Tests on Windows must not create it."""
    if os.environ.get("NETINJA_PUBLIC_SOURCE_PIN", "").strip():
        return True
    return os.name != "nt"


async def apply_state(
    state: dict[str, Any],
    *,
    runner: Runner | None = None,
    install_unit: bool = True,
) -> dict[str, list[dict[str, Any]]]:
    """Persist the pin set and install it. Does not flush peer NAT chains."""
    if not _install_enabled():
        return {
            "addresses": _addresses(state.get("addresses")),
            "peers": _peers(state.get("peers")),
        }
    clean = save_state(state)
    path = script_path()
    path.write_text(render_script(clean), encoding="utf-8")
    try:
        path.chmod(0o755)
    except OSError:
        pass
    if shutil.which("nft") or shutil.which("sh"):
        run = runner or process_run
        await execute(run, ["sh", str(path)], check=False, timeout=30)
        await _retarget_masquerade(run)
        await _drop_pinned_conntrack(clean["addresses"], run)
        if install_unit:
            await ensure_unit(path, runner=run)
    return clean


async def remember_address(ip: str, mark: int = 0, *, runner: Runner | None = None) -> None:
    """Keep one Xray source in the pin table without dropping other nodes."""
    from agent.support.peer_egress import egress_mark, public_exit_ipv4

    address = public_exit_ipv4(ip)
    if not address:
        return
    wanted = int(mark) if int(mark) > 0 else egress_mark(address)
    current = load_state()
    current["addresses"] = [
        row for row in current["addresses"] if row["ip"] != address
    ]
    current["addresses"].append({"ip": address, "mark": wanted})
    await apply_state(current, runner=runner)


async def replace_peers(
    rows: list[dict[str, Any]],
    *,
    runner: Runner | None = None,
) -> None:
    """Replace tunnel-source SNAT rows. Xray address pins stay as they are."""
    current = load_state()
    current["peers"] = _peers(rows)
    await apply_state(current, runner=runner)


async def rebuild_from_host(
    store: Any,
    config_path: str | Path | None,
    *,
    runner: Runner | None = None,
) -> dict[str, list[dict[str, Any]]]:
    """Rebuild the pin file from the Xray config and saved peer egress state."""
    from agent.support.xray_exit_bind import ensure_source_address_route, pins_from_outbounds

    previous = load_state()
    addresses = previous["addresses"]
    path = Path(config_path) if config_path else None
    if path is not None and path.is_file():
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            payload = None
        if isinstance(payload, dict):
            addresses = pins_from_outbounds(list(payload.get("outbounds") or []))
    peers = previous["peers"]
    try:
        from agent.support.peer_egress import _pin_rows, all_desired_rules_from_store

        peers = _pin_rows(await all_desired_rules_from_store(store))
    except Exception:
        peers = previous["peers"]
    clean = await apply_state({"addresses": addresses, "peers": peers}, runner=runner)
    for row in clean["addresses"]:
        try:
            await ensure_source_address_route(str(row["ip"]), runner=runner)
        except Exception:
            continue
    return clean


_HANDLE_RE = re.compile(r"# handle (\d+)\s*$")
_OIF_RE = re.compile(r'oifname (?:"([^"]+)"|(\S+))')
_IIF_RE = re.compile(r'iifname (?:"([^"]+)"|(\S+))')
_COMMENT_RE = re.compile(r'comment "([^"]*)"')


def masquerade_rewrites(listing: str) -> list[tuple[str, list[str]]]:
    """Masquerade rules that still match a pinned source, and their replacement."""
    found: list[tuple[str, list[str]]] = []
    for line in listing.splitlines():
        if "masquerade" not in line or "@pinned" in line:
            continue
        handle = _HANDLE_RE.search(line.strip())
        oif = _OIF_RE.search(line)
        if handle is None or oif is None:
            continue
        args = ["add", "rule", "inet", "netinja_egress", "postrouting"]
        iif = _IIF_RE.search(line)
        if iif is not None:
            args.extend(["iifname", iif.group(1) or iif.group(2)])
        args.extend(["oifname", oif.group(1) or oif.group(2), "ip", "saddr", "!=", "@pinned", "masquerade"])
        comment = _COMMENT_RE.search(line)
        if comment is not None:
            args.extend(["comment", comment.group(1)])
        found.append((handle.group(1), args))
    return found


async def _retarget_masquerade(runner: Runner) -> None:
    """Point an already-installed MASQUERADE away from pinned additional IPs.

    ``accept`` in the earlier pin chain does not stop a later base chain, so
    the MASQUERADE rule itself has to ignore those sources.
    """
    if not shutil.which("nft"):
        return
    try:
        listed = await execute(
            runner,
            ["nft", "-a", "list", "chain", "inet", "netinja_egress", "postrouting"],
            check=False,
            timeout=10,
        )
    except Exception:
        return
    listing = str(getattr(listed, "stdout", "") or "")
    if "masquerade" not in listing:
        return
    from agent.support.peer_egress import _nft

    for handle, args in masquerade_rewrites(listing):
        await execute(
            runner,
            ["nft", "delete", "rule", "inet", "netinja_egress", "postrouting", "handle", handle],
            check=False,
            timeout=10,
        )
        await _nft(runner, args)


async def _drop_pinned_conntrack(addresses: list[dict[str, Any]], runner: Runner) -> None:
    """Forget NAT entries that already rewrote this source to the primary IP."""
    from agent.support.peer_egress import _flush_conntrack

    for row in addresses:
        await _flush_conntrack(runner, str(row.get("ip") or ""))


async def ensure_unit(script: Path, *, runner: Runner | None = None) -> None:
    """Oneshot that reapplies the pin after boot, independent of peer NAT."""
    if not shutil.which("systemctl"):
        return
    unit = "\n".join(
        [
            "[Unit]",
            "Description=Netinja additional-IP source pin",
            "After=network-online.target",
            "Wants=network-online.target",
            "",
            "[Service]",
            "Type=oneshot",
            f"ExecStart={script}",
            "RemainAfterExit=yes",
            "",
            "[Install]",
            "WantedBy=multi-user.target",
            "",
        ]
    )
    try:
        _UNIT_PATH.parent.mkdir(parents=True, exist_ok=True)
        previous = _UNIT_PATH.read_text(encoding="utf-8") if _UNIT_PATH.is_file() else ""
        run = runner or process_run
        if previous != unit:
            _UNIT_PATH.write_text(unit, encoding="utf-8")
            await execute(run, ["systemctl", "daemon-reload"], check=False, timeout=30)
        await execute(run, ["systemctl", "enable", _UNIT_NAME], check=False, timeout=30)
    except OSError:
        return


def _addresses(raw: Any) -> list[dict[str, Any]]:
    from agent.support.peer_egress import egress_mark, public_exit_ipv4

    found: list[dict[str, Any]] = []
    seen: set[str] = set()
    if not isinstance(raw, list):
        return found
    for row in raw:
        if not isinstance(row, dict):
            continue
        address = public_exit_ipv4(row.get("ip") or row.get("sendThrough"))
        if not address or address in seen:
            continue
        try:
            mark = int(row.get("mark") or 0)
        except (TypeError, ValueError):
            mark = 0
        if mark <= 0:
            mark = egress_mark(address)
        seen.add(address)
        found.append({"ip": address, "mark": mark})
    return found


def _peers(raw: Any) -> list[dict[str, str]]:
    from agent.support.peer_egress import public_exit_ipv4

    found: list[dict[str, str]] = []
    seen: set[tuple[str, str]] = set()
    if not isinstance(raw, list):
        return found
    for row in raw:
        if not isinstance(row, dict):
            continue
        snat = public_exit_ipv4(row.get("snat") or row.get("ip"))
        cidr = str(row.get("cidr") or "").strip()
        addr = str(row.get("addr") or "").strip()
        if not cidr and addr:
            cidr = f"{addr}/32"
        if not snat or not _public_host_cidr(cidr):
            continue
        key = (cidr, snat)
        if key in seen:
            continue
        seen.add(key)
        found.append({"cidr": cidr, "snat": snat})
    return found


def _public_host_cidr(cidr: str) -> bool:
    try:
        network = ipaddress.ip_network(cidr, strict=False)
    except ValueError:
        return False
    return (
        network.version == 4
        and network.prefixlen == 32
        and not network.network_address.is_unspecified
    )
